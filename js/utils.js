/* ---------- Datum ---------- */
const DateUtils = {
  /** Gibt das Datum ohne Uhrzeit (00:00 Uhr) zurück */
  startOfDay(date) {
    const d = new Date(date);
    d.setHours(0, 0, 0, 0);
    return d;
  },

  /** Addiert (oder subtrahiert) Tage */
  addDays(date, days) {
    const d = new Date(date);
    d.setDate(d.getDate() + days);
    return d;
  },

  /** Montag der Woche, in der das Datum liegt */
  startOfWeek(date) {
    const d = DateUtils.startOfDay(date);
    const diff = (d.getDay() + 6) % 7; // Montag = 0 … Sonntag = 6
    return DateUtils.addDays(d, -diff);
  },

  isSameDay(a, b) {
    return a.toDateString() === b.toDateString();
  },

  /** Eindeutiger Schlüssel wie "2026-10-12" */
  toKey(date) {
    const y = date.getFullYear();
    const m = String(date.getMonth() + 1).padStart(2, '0');
    const d = String(date.getDate()).padStart(2, '0');
    return `${y}-${m}-${d}`;
  },

  /** Wochentag-Schlüssel ("mo" … "so") passend zu WEEKDAYS in data.js */
  weekdayKey(date) {
    return ['so', 'mo', 'di', 'mi', 'do', 'fr', 'sa'][date.getDay()];
  },

  /** Kalenderwoche nach ISO 8601 */
  isoWeek(date) {
    const d = new Date(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()));
    const day = d.getUTCDay() || 7;
    d.setUTCDate(d.getUTCDate() + 4 - day);
    const yearStart = new Date(Date.UTC(d.getUTCFullYear(), 0, 1));
    return Math.ceil(((d - yearStart) / 86400000 + 1) / 7);
  },
};

/* ---------- Zahlen & Texte formatieren ---------- */
const Format = {
  number(value) {
    return Math.round(value).toLocaleString('de-DE');
  },

  /** 95 → "1 h 35 min" */
  minutes(value) {
    const total = Math.round(value);
    const h = Math.floor(total / 60);
    const m = total % 60;
    if (h === 0) return `${m} min`;
    if (m === 0) return `${h} h`;
    return `${h} h ${m} min`;
  },

  /** 7.4 → "7,4 h" */
  hours(value) {
    return `${value.toLocaleString('de-DE', { minimumFractionDigits: 1, maximumFractionDigits: 1 })} h`;
  },

  /** 12500 → "12,5k" (für Achsenbeschriftungen) */
  compact(value) {
    if (Math.abs(value) >= 1000) {
      return `${(value / 1000).toLocaleString('de-DE', { maximumFractionDigits: 1 })}k`;
    }
    return Format.number(value);
  },

  date(date, options) {
    return date.toLocaleDateString('de-DE', options);
  },
};

/* ---------- CSS & HTML ---------- */

/** Liest eine CSS-Variable aus (z. B. cssVar('--accent')) */
function cssVar(name) {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim();
}

/** Macht aus "#5b5bd6" + 0.4 → "rgba(91, 91, 214, 0.4)" */
function withAlpha(hex, alpha) {
  const clean = hex.replace('#', '');
  const full = clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean;
  const num = parseInt(full, 16);
  return `rgba(${(num >> 16) & 255}, ${(num >> 8) & 255}, ${num & 255}, ${alpha})`;
}

/** Schützt vor HTML-Einschleusung bei Nutzereingaben */
function escapeHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Tiefe Kopie eines einfachen Objekts */
function clone(obj) {
  return JSON.parse(JSON.stringify(obj));
}

/* ---------- Speicher (localStorage) ---------- */
const Storage = {
  get(key, fallback) {
    try {
      const raw = localStorage.getItem(key);
      return raw ? JSON.parse(raw) : fallback;
    } catch (e) {
      return fallback;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem(key, JSON.stringify(value));
    } catch (e) {
      /* z. B. im privaten Modus – dann wird einfach nicht gespeichert */
    }
  },
};

/* ---------- Toast-Meldung ---------- */
let toastTimer;
function showToast(message) {
  const el = document.getElementById('toast');
  el.textContent = message;
  el.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.remove('show'), 2200);
}

/* ---------- Bestätigungsdialog ---------- */
/**
 * Zeigt einen eigenen Bestätigungsdialog (statt confirm()).
 * Gibt ein Promise zurück: true = bestätigt, false = abgebrochen.
 * Nutzung: if (await confirmAction('Text', 'Löschen')) { … }
 */
function confirmAction(text, okLabel = 'Bestätigen', title = 'Bist du sicher?') {
  const modal = document.getElementById('confirmModal');
  document.getElementById('confirmTitle').textContent = title;
  document.getElementById('confirmText').textContent = text;
  document.getElementById('confirmOk').textContent = okLabel;
  modal.returnValue = '';
  modal.showModal();
  document.getElementById('confirmCancel').focus();

  return new Promise((resolve) => {
    modal.addEventListener('close', () => resolve(modal.returnValue === 'ok'), { once: true });
  });
}

